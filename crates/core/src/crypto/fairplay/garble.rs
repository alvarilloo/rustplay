// Port of UxPlay lib/playfair/hand_garble.c. All arithmetic is done in i64 so no
// intermediate can overflow; results are truncated to u8 on store, which matches
// the C code because only +, -, *, &, |, ^, << and ~ feed those stores, while the
// divisions and right shifts only ever see small non-negative values.

macro_rules! v {
    ($b:ident[$i:expr]) => {
        i64::from($b[($i) as usize])
    };
}

fn ror8w(input: i64, count: i64) -> i64 {
    if count == 0 {
        return 0;
    }
    let i = input & 0xff;
    (i >> count) | (i << (8 - count))
}

fn rol8w(input: i64, count: i64) -> i64 {
    if count == 0 {
        return 0;
    }
    let i = input & 0xff;
    ((i << count) & 0xff) | (i >> (8 - count))
}

fn rol32w(input: i64, count: i64) -> i64 {
    if count == 0 {
        return 0;
    }
    let i = input & 0xff;
    (i << count) ^ (i >> (8 - count))
}

fn rol8(input: i64, count: i64) -> i64 {
    let i = input & 0xff;
    ((i << count) & 0xff) | (i >> (8 - count))
}

fn rol8x(input: i64, count: i64) -> i64 {
    let i = input & 0xff;
    (i << count) | (i >> (8 - count))
}

